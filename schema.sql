-- Clean up existing tables
DROP TABLE IF EXISTS messages CASCADE;
DROP TABLE IF EXISTS participants CASCADE;

-- Create messages table with partitioning
CREATE TABLE messages (
    id UUID NOT NULL,
    sender_name VARCHAR(255) NOT NULL,
    timestamp_ms BIGINT NOT NULL,
    content TEXT,
    photos JSONB,
    videos JSONB,
    audio JSONB,
    reactions JSONB,
    is_geoblocked_for_viewer BOOLEAN DEFAULT FALSE,
    is_unsent_image_by_messenger_kid_parent BOOLEAN DEFAULT FALSE,
    delivered BOOLEAN DEFAULT TRUE,
    read BOOLEAN DEFAULT FALSE,
    reply_to UUID,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT messages_id_created_at_unique UNIQUE (id, created_at),
    FOREIGN KEY (reply_to, created_at) REFERENCES messages(id, created_at)
) PARTITION BY RANGE (created_at);

